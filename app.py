@app.route("/monthly-report")
def monthly_report():
    if "user_id" not in session:
        return redirect("/login")

    month = request.args.get("month")

    if month:
        cursor.execute("""
            SELECT * FROM transactions
            WHERE user_id = %s
            AND TO_CHAR(date, 'YYYY-MM') = %s
            ORDER BY date DESC
        """, (session["user_id"], month))
    else:
        cursor.execute("""
            SELECT * FROM transactions
            WHERE user_id = %s
            ORDER BY date DESC
        """, (session["user_id"],))

    data = cursor.fetchall()

    income = sum(t[2] for t in data if t[3] == "income")
    expense = sum(t[2] for t in data if t[3] == "expense")
    balance = income - expense

    return render_template(
        "monthly_report.html",
        transactions=data,
        income=income,
        expense=expense,
        balance=balance,
        month=month
    )

@app.route("/export-pdf")
def export_pdf():
    if "user_id" not in session:
        return redirect("/login")

    month = request.args.get("month", "")

    if month:
        cursor.execute("""
            SELECT * FROM transactions
            WHERE user_id = %s
            AND TO_CHAR(date, 'YYYY-MM') = %s
            ORDER BY date DESC
        """, (session["user_id"], month))
    else:
        cursor.execute("""
            SELECT * FROM transactions
            WHERE user_id = %s
            ORDER BY date DESC
        """, (session["user_id"],))

    data = cursor.fetchall()

    income = sum(t[2] for t in data if t[3] == "income")
    expense = sum(t[2] for t in data if t[3] == "expense")
    balance = income - expense

    response = make_response()
    response.headers["Content-Type"] = "application/pdf"
    response.headers["Content-Disposition"] = "attachment; filename=monthly_report.pdf"

    pdf = canvas.Canvas(response.stream, pagesize=A4)
    width, height = A4

    y = height - 50

    pdf.setFont("Helvetica-Bold", 16)
    pdf.drawString(50, y, "Smart Expense Tracker - Monthly Report")

    y -= 30
    pdf.setFont("Helvetica", 11)
    pdf.drawString(50, y, f"Month: {month if month else 'All'}")

    y -= 30
    pdf.drawString(50, y, f"Total Income: Rs. {income}")
    y -= 20
    pdf.drawString(50, y, f"Total Expense: Rs. {expense}")
    y -= 20
    pdf.drawString(50, y, f"Balance: Rs. {balance}")

    y -= 40
    pdf.setFont("Helvetica-Bold", 11)
    pdf.drawString(50, y, "Title")
    pdf.drawString(200, y, "Amount")
    pdf.drawString(300, y, "Type")
    pdf.drawString(400, y, "Date")

    pdf.setFont("Helvetica", 10)

    for t in data:
        y -= 20

        if y < 50:
            pdf.showPage()
            y = height - 50

        pdf.drawString(50, y, str(t[1]))
        pdf.drawString(200, y, f"Rs. {t[2]}")
        pdf.drawString(300, y, str(t[3]))
        pdf.drawString(400, y, t[4].strftime("%d-%m-%Y"))

    pdf.save()
    return response

