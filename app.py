from flask import Flask, render_template, request, redirect, session
from werkzeug.security import generate_password_hash, check_password_hash
from dotenv import load_dotenv
from flask import make_response
from reportlab.pdfgen import canvas
from reportlab.lib.pagesizes import A4
import os
import psycopg2
import psycopg2.errors

load_dotenv()

app = Flask(__name__)
app.secret_key = "smart_expense_secret_key"

conn = psycopg2.connect(os.getenv("DATABASE_URL"))
cursor = conn.cursor()

cursor.execute("""
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL
)
""")

cursor.execute("""
CREATE TABLE IF NOT EXISTS transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT,
    amount FLOAT,
    type TEXT,
    date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    user_id BIGINT,
    FOREIGN KEY (user_id) REFERENCES users(id)
)
""")
conn.commit()


@app.route("/")
def home():
    if "user_id" not in session:
        return redirect("/login")

    filter_type = request.args.get("type", "all")
    search = request.args.get("search", "")

    query = "SELECT * FROM transactions WHERE user_id = %s"
    params = [session["user_id"]]

    if filter_type == "income":
        query += " AND type = %s"
        params.append("income")
    elif filter_type == "expense":
        query += " AND type = %s"
        params.append("expense")

    if search:
        query += " AND title ILIKE %s"
        params.append(f"%{search}%")

    query += " ORDER BY id DESC"

    cursor.execute(query, tuple(params))
    transactions = cursor.fetchall()

    cursor.execute(
        "SELECT * FROM transactions WHERE user_id = %s",
        (session["user_id"],)
    )
    all_transactions = cursor.fetchall()

    total_income = sum(t[2] for t in all_transactions if t[3] == "income")
    total_expense = sum(t[2] for t in all_transactions if t[3] == "expense")
    balance = total_income - total_expense

    return render_template(
        "index.html",
        transactions=transactions,
        total_income=total_income,
        total_expense=total_expense,
        balance=balance,
        filter_type=filter_type,
        search=search
    )


@app.route("/register", methods=["GET", "POST"])
def register():
    if request.method == "POST":
        name = request.form["name"]
        email = request.form["email"].strip().lower()
        raw_password = request.form["password"]

        hashed_password = generate_password_hash(raw_password, method="pbkdf2:sha256")

        try:
            cursor.execute(
                "INSERT INTO users (name, email, password) VALUES (%s, %s, %s)",
                (name, email, hashed_password)
            )
            conn.commit()
            return redirect("/login")

        except psycopg2.errors.UniqueViolation:
            conn.rollback()
            return "Email already registered. Please login."

    return render_template("register.html")


